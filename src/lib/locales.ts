export const FULL_LANGUAGES: LocaleOption[] = Object.entries(LANGUAGE_NAMES)
  .map(([code, name]) => ({ code, name }))
  .sort((a, b) => a.name.localeCompare(b.name));

export const FULL_REGIONS: LocaleOption[] = Object.entries(REGION_NAMES)
  .map(([code, name]) => ({ code, name }))
  .sort((a, b) => a.name.localeCompare(b.name));

export function getLanguageName(code: string): string {
  const languageCode = code.split(/[-_]/)[0]?.toLowerCase() ?? code.toLowerCase();
  return LANGUAGE_NAMES[languageCode] ?? code;
}

export function getRegionName(code: string): string {
  return REGION_NAMES[code.toUpperCase()] ?? code;
}

export function getLanguageCode(displayName: string): string {
  return FULL_LANGUAGES.find(
    (language) => language.name.toLowerCase() === displayName.toLowerCase()
  )?.code ?? "en";
}

export function getRegionCode(displayName: string): string {
  return FULL_REGIONS.find(
    (region) => region.name.toLowerCase() === displayName.toLowerCase()
  )?.code ?? "US";
}

export function getAvailableLanguages(): string[] {
  return FULL_LANGUAGES.map((language) => language.name);
}

export function getAvailableRegions(): string[] {
  return FULL_REGIONS.map((region) => region.name);
}
